import {
  authorizeWorkspaceApi,
  resolveRequestId,
  workspaceError,
  workspaceJson,
} from "@/app/api/v1/workspace/_shared";
import {
  readGeminiConfig,
  runUtilityTaskWithGemini,
  type UtilitySourceExcerpt,
  type UtilityTaskKind,
} from "@/server/ai/gemini-client";
import {
  loadKnowledgeDocumentsAndSpaces,
  recordWorkspaceNotification,
} from "@/server/knowledge/repository";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

const ALLOWED_TASKS = new Set<UtilityTaskKind>([
  "summary",
  "translate",
  "checklist",
  "report",
  "email",
]);

export async function POST(request: Request): Promise<Response> {
  const requestId = resolveRequestId(request);
  const auth = await authorizeWorkspaceApi(request, requestId);
  if (!auth.ok) return auth.response;

  if (!readGeminiConfig()) {
    return workspaceError(
      503,
      "GEMINI_NOT_CONFIGURED",
      "Chưa cấu hình GEMINI_API_KEY trên máy chủ.",
      requestId,
    );
  }

  let body: {
    task?: unknown;
    documentIds?: unknown;
    pastedText?: unknown;
    pastedTitle?: unknown;
    targetLanguage?: unknown;
    customInstruction?: unknown;
    locale?: unknown;
  };
  try {
    body = (await request.json()) as typeof body;
  } catch {
    return workspaceError(400, "INVALID_JSON", "Payload không hợp lệ.", requestId);
  }

  const task = typeof body.task === "string" && ALLOWED_TASKS.has(body.task as UtilityTaskKind)
    ? (body.task as UtilityTaskKind)
    : null;
  if (!task) {
    return workspaceError(400, "INVALID_TASK", "Loại tiện ích AI không hợp lệ.", requestId);
  }

  const locale = body.locale === "en" ? "en" : "vi";
  const documentIds = Array.isArray(body.documentIds)
    ? body.documentIds.filter((id): id is string => typeof id === "string" && id.trim().length > 0).slice(0, 5)
    : [];
  const pastedText = typeof body.pastedText === "string" ? body.pastedText.trim() : "";
  const pastedTitle =
    typeof body.pastedTitle === "string" && body.pastedTitle.trim().length > 0
      ? body.pastedTitle.trim().slice(0, 120)
      : locale === "en"
        ? "Pasted workspace excerpt"
        : "Văn bản dán trực tiếp";
  const targetLanguage =
    typeof body.targetLanguage === "string" ? body.targetLanguage.trim().slice(0, 48) : undefined;
  const customInstruction =
    typeof body.customInstruction === "string"
      ? body.customInstruction.trim().slice(0, 400)
      : undefined;

  const sources: UtilitySourceExcerpt[] = [];
  const sourcesUsed: Array<{ documentId: string | null; title: string; spaceName: string | null }> = [];

  if (documentIds.length > 0) {
    const { documents } = await loadKnowledgeDocumentsAndSpaces(auth.access);
    for (const id of documentIds) {
      const doc = documents.find(
        (d) => d.summary.id === id && d.summary.processing.kind === "ready",
      );
      if (!doc || doc.chunks.length === 0) continue;
      const joined = doc.chunks
        .map((chunk) => `[${chunk.heading} — ${chunk.locator}]\n${chunk.content}`)
        .join("\n\n");
      sources.push({
        documentId: doc.summary.id,
        title: doc.summary.name,
        spaceName: doc.summary.space.name,
        content: joined,
      });
      sourcesUsed.push({
        documentId: doc.summary.id,
        title: doc.summary.name,
        spaceName: doc.summary.space.name,
      });
    }
  }

  if (pastedText.length >= 15) {
    sources.push({
      title: pastedTitle,
      content: pastedText.slice(0, 15_000),
    });
    sourcesUsed.push({
      documentId: null,
      title: pastedTitle,
      spaceName: null,
    });
  }

  if (sources.length === 0) {
    return workspaceError(
      400,
      "MISSING_SOURCE",
      "Hãy chọn ít nhất 1 tài liệu Sẵn sàng hoặc dán ít nhất 15 ký tự văn bản nguồn.",
      requestId,
    );
  }

  const result = await runUtilityTaskWithGemini({
    task,
    targetLanguage,
    customInstruction,
    sources,
    locale,
  });

  if (!result) {
    return workspaceError(
      502,
      "AI_UTILITY_FAILED",
      "Hệ thống AI tạm thời không phản hồi được cho tác vụ này. Vui lòng thử lại.",
      requestId,
    );
  }

  const taskLabels: Record<UtilityTaskKind, { vi: string; en: string }> = {
    summary: { vi: "Tóm tắt", en: "Summary" },
    translate: { vi: "Dịch thuật", en: "Translation" },
    checklist: { vi: "Checklist", en: "Checklist" },
    report: { vi: "Báo cáo", en: "Report" },
    email: { vi: "Soạn Email", en: "Email draft" },
  };

  await recordWorkspaceNotification(auth.access, {
    kind: "utility_completed",
    title:
      locale === "en"
        ? `AI ${taskLabels[task].en}: ${result.title}`
        : `Tiện ích ${taskLabels[task].vi}: ${result.title}`,
    description:
      locale === "en"
        ? `Generated by UPTECH AI from ${sourcesUsed.length} source(s).`
        : `Hoàn tất bằng Trợ lý AI từ ${sourcesUsed.length} nguồn dữ liệu.`,
    href: "/utility",
    actionLabel: locale === "en" ? "Open AI Utilities" : "Mở Tiện ích AI",
  });

  return workspaceJson(
    {
      ok: true,
      task,
      model: result.model,
      title: result.title,
      output: result.output,
      takeaways: result.takeaways,
      sourcesUsed,
      disclaimer:
        locale === "en"
          ? "Generated by AI directly from your selected source(s). Verify numbers before external distribution."
          : "Nội dung do hệ thống AI tổng hợp trực tiếp từ nguồn bạn đã chọn. Hãy đối chiếu số liệu trước khi phát hành.",
    },
    200,
    requestId,
  );
}
